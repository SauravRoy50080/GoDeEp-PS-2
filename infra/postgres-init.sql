\set ON_ERROR_STOP on
\getenv app_password GODEEP_APP_DB_PASSWORD
CREATE ROLE godeep_app LOGIN PASSWORD :'app_password'
    NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION;
ALTER DATABASE godeep OWNER TO godeep_app;
\connect godeep
REVOKE ALL ON DATABASE godeep FROM PUBLIC;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA public TO godeep_app;
